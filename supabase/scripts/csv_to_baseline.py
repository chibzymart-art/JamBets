"""Turn the CSV exported from supabase/scripts/export_schema_baseline.sql into a baseline SQL file.

Usage: python supabase/scripts/csv_to_baseline.py "Supabase Snippet Untitled query.csv" supabase/baseline/live_schema.sql
"""
import csv
import sys
from datetime import date

csv.field_size_limit(10**9)

SECTIONS = {
    10: 'Extensions', 15: 'Schemas', 20: 'Sequences', 30: 'Tables', 40: 'Constraints',
    45: 'Foreign keys', 50: 'Indexes', 60: 'Functions', 70: 'Views', 72: 'Materialized views',
    80: 'Triggers', 90: 'Row level security', 95: 'Policies', 99: 'Table privileges: reset',
    100: 'Table privileges: grants', 105: 'Function privileges: reset', 110: 'Function privileges: grants',
}


def main(src: str, dst: str) -> None:
    rows = sorted(csv.DictReader(open(src, encoding='utf-8')), key=lambda r: (int(r['ord']), r['obj']))
    out = [
        f'-- Live schema baseline for Oddsbanta (Supabase project vepcoopomlfjageijsew), exported {date.today().isoformat()}.',
        '-- Generated by supabase/scripts/export_schema_baseline.sql from the live catalog. Schema only, no data.',
        '-- This is the source of truth for what the database looks like today: diff against it before writing',
        '-- a migration, and regenerate it after applying one. It is a reference snapshot, not a migration:',
        '-- do not run it against production.',
        '',
    ]
    current = None
    for r in rows:
        ord_ = int(r['ord'])
        if ord_ != current:
            current = ord_
            out += ['', '-- ' + '-' * 75, f'-- {SECTIONS.get(ord_, ord_)}', '-- ' + '-' * 75, '']
        ddl = r['ddl'].rstrip()
        if not ddl.endswith(';'):
            ddl += ';'
        out.append(ddl)
        if '\n' in ddl:
            out.append('')
    open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'wrote {len(rows)} statements to {dst}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
